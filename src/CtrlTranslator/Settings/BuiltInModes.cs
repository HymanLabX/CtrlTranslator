namespace CtrlTranslator.Settings;

/// <summary>
/// 规格书定义的四个内置翻译模式。
/// </summary>
/// <remarks>
/// ⚠️ 改动本文件里任何一段提示词文字，都必须把 <see cref="AppSettings.CurrentPromptVersion"/> 加一。
/// 提示词会被写进 settings.json，不加版本号的话老用户永远用的还是旧提示词。
///
/// ⚠️ 词典格式只能由 <see cref="DictionaryMarkerTag"/> 这个标记触发，
/// 该标记由 PromptBuilder 按词数阈值决定是否添加。
/// 提示词里绝不能再写「或短语」「不构成完整句子时」之类让模型自行判断的措辞 ——
/// 那会让模型绕开词数阈值，把划到的半句话当成词条来分析（已踩坑）。
///
/// ⚠️ 这里的提示词<b>只管翻译风格，不提任何语言</b>。
/// 「译成什么语言」「原文已经是目标语言时怎么办」「例句用哪门语言写」由
/// <see cref="CtrlTranslator.Translation.PromptBuilder"/> 生成一段语言指令拼在最前面。
/// 这样用户写自己的模式时不用学任何占位符语法，也不会因为漏写而静默失效。
///
/// ⚠️ 下面四段模板仍用 $$""" 而不是 $"""：正文里有 { } 字面量（如格式示例），
/// 单个 $ 会把它们当插值起点，编译不过。用 $$ 后单个 { } 才是字面量。
/// </remarks>
public static class BuiltInModes
{
    /// <summary>
    /// 触发词典格式的标记。由 PromptBuilder 按词数阈值决定是否加在用户内容前面。
    /// 提示词里引用的也是这个常量，避免两边写法漂移。
    /// </summary>
    public const string DictionaryMarkerTag = "[请按词典条目格式输出]";

    /// <summary>
    /// 四个模式共用的收尾规则：禁止自作主张用词典格式，只有见到标记才用。
    /// </summary>
    private const string DictionaryRule = $"""
        只有当输入以 {DictionaryMarkerTag} 开头时，才改为输出词典条目。
        这行标记由程序自动添加，不是待翻译内容，不要输出它。词典条目格式严格如下：
        /音标/
        词性. 释义1；释义2；释义3
        例：一个英文例句 —— 该例句的中文翻译
        没有这行标记时，无论输入多短、多不完整，都一律按普通译文输出。
        """;

    /// <summary>
    /// 四个模式共用的片段规则：划词划到的经常是半句话，照样只给一句译文。
    /// </summary>
    private const string FragmentRule = """
        用户划取的往往是文档中的一个片段，可能是短语、动名词结构、从句或半句话，不构成完整句子。
        这种情况照样只输出一句译文：不要注音标、不要标注词性或成分、
        不要用「；」罗列多个候选译法，只给最贴合上下文的那一个。
        """;

    /// <summary>
    /// 深度翻译三节输出的格式约定，四个模式共用。
    /// </summary>
    /// <remarks>
    /// <para>
    /// ⚠️ 三个小节标题是 <see cref="CtrlTranslator.Translation.DeepResultParser"/> 分段的<b>唯一</b>依据。
    /// 改这里的标题文字，必须同步改解析器里的常量，否则整块结果会被当成译文塞进第一节。
    /// </para>
    /// <para>
    /// ⚠️ 这里说的「例句语言 / 对照语言」由 <see cref="CtrlTranslator.Translation.DeepPromptBuilder"/>
    /// 在开头的语言指令里定义，<b>和本次翻译方向不是一回事</b>：
    /// 查英文单词 harness 时翻译方向是「译成中文」，但用户要的显然是英文例句。
    /// 早先这里直接写翻译方向，结果查英文词得到一堆中文例句（已踩坑）。
    /// </para>
    /// </remarks>
    private const string DeepOutputFormat = $$"""
        严格按下面的格式输出。三个小节标题必须原样单独占一行，不要加粗、不要编号、不要改字，
        三节都要有，即使某节内容是「无」。

        【译文】
        把原文翻译成目标语言之后的结果，正文必须是目标语言，
        绝对不能把原文原样抄一遍——写出来和原文是同一种语言就是错的。
        这一节只对应原文本身，严禁扩写：不要在这里写例句，不要补充原文没有的背景，
        更不要因为原文短就自己想象一个上下文、写成一整段话。
        原文只有一个词，这一节就只有那个词的意思，一行就够。
        保留原文的段落结构与换行，不要解释，不要加「译文：」之类的标签。

        当输入以 {{DictionaryMarkerTag}} 开头时，说明用户查的是一个单词或短语，
        这一节改写成词条，具体格式以最后那段「本次的词条格式」为准。
        这行标记由程序自动添加，不是待翻译内容，不要把它输出出来。
        没有这行标记时，一律给完整译文，不要注音标、不要罗列义项。

        【例句】
        2-3 条例句，展示原文里的关键表达在真实语境中怎么用。
        例句本身用开头指定的「例句语言」写，每条占两行：第一行是例句，
        第二行以「—— 」开头给出它的「对照语言」译文。
        例句必须自然、完整、像真实文本里会出现的句子，不要为了套格式而生造。
        原文是长段落时，挑其中最值得学的那一两个表达来举例，不要复述整段。

        【搭配】
        围绕原文里的关键表达，给出「例句语言」中值得记住的固定搭配，每行一条，
        格式为「搭配 — 一句话说明什么时候用」，搭配本身用「例句语言」，说明用「对照语言」。
        最多 5 条，宁少勿滥。原文是长段落时只挑关键术语的搭配。
        确实没有值得说的（比如原文就是一句大白话），只写一行「无」。
        """;

    /// <summary>
    /// 卡片上那行摘要：一句话说清这个模式偏向什么，让人选之前就知道差别，
    /// 不用点进去读一整段提示词。
    /// </summary>
    /// <remarks>
    /// 刻意<b>不</b>作为字段挂到 <see cref="TranslationMode"/> 上：那样要跟着序列化，
    /// 而回填内置内容的那段逻辑只在 <see cref="AppSettings.PromptVersion"/> 升级时才跑，
    /// 老配置永远拿不到。放这儿按 Id 查表，没有迁移问题。
    /// </remarks>
    private static readonly Dictionary<string, string> Summaries = new(StringComparer.Ordinal)
    {
        ["auto"] = "默认取舍，什么都能翻，不偏向任何文体",
        ["academic"] = "术语用学科通行译法，公式和文献编号原样保留",
        ["social"] = "自然口语，像人说话，绝不要翻译腔",
        ["business"] = "得体书面语，措辞专业、简洁、礼貌",
    };

    /// <summary>取内置模式的一句话摘要；自建模式返回 null。</summary>
    public static string? SummaryOrNull(string id) => Summaries.GetValueOrDefault(id);

